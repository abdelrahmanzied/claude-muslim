# Dev-only: regenerates plugin/src/features/salah/jumuah-font.ts, the Tajawal Regular subset the Jumu'ah athan card embeds.
# The desktop's Client tree must stay under 100,000 characters (DESIGN.md), and the athan card already holds the photo
# and Aref Ruqaa, so only the glyphs the verse and its reference need are kept (every layout feature is kept, so the
# letters join and the marks sit as in the whole font). Input: the shared Tajawal WOFF2 in the repo; no download.
#
#   python3 -m venv /tmp/fontenv && /tmp/fontenv/bin/pip install fonttools brotli
#   /tmp/fontenv/bin/python scripts/font/jumuah-subset.py
#
# Tajawal is SIL OFL 1.1 (plugin/src/shared/font/fonts/OFL.txt).
import base64, io, re, sys
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[2]
shared = (root / 'plugin/src/shared/font/tajawal-embedded.ts').read_text()
regular = re.search(r"TAJAWAL_REGULAR_WOFF2 = '([^']+)'", shared).group(1)
ayah = (root / 'plugin/src/shared/friday/jumuah-ayah.ts').read_text()
text = re.search(r"JUMUAH_AYAH = '([^']*)'", ayah).group(1) + re.search(r"JUMUAH_REF = '([^']*)'", ayah).group(1)
# The brackets, a space, and the verse without its tashkeel (the setting may strip it: the same base letters, so nothing new).
text += '﴾﴿  '
font = TTFont(io.BytesIO(base64.b64decode(regular)))
opts = subset.Options()
opts.flavor = 'woff2'
opts.layout_features = ['*']
opts.notdef_outline = True
opts.name_IDs = [1, 2]
opts.drop_tables += ['DSIG']
sub = subset.Subsetter(opts)
sub.populate(text=text)
sub.subset(font)
out = io.BytesIO()
opts.flavor = 'woff2'
font.flavor = 'woff2'
font.save(out)
b64 = base64.b64encode(out.getvalue()).decode()
(root / 'plugin/src/features/salah/jumuah-font.ts').write_text(
    "// Tajawal Regular (SIL Open Font License 1.1, see ../../shared/font/fonts/OFL.txt), subset to the glyphs of Jumu'ah's verse and its\n"
    "// reference, with every layout feature kept. Generated by scripts/font/jumuah-subset.py; do not edit.\n"
    f"export const TAJAWAL_JUMUAH = '{b64}'\n")
print(len(b64), 'base64 chars', len(out.getvalue()), 'bytes', len(font.getGlyphOrder()), 'glyphs')
